/** Fill {placeholders}: fmt("{n} pieces", { n: 3 }) → "3 pieces" */
export function fmt(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}
